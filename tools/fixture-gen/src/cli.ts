// Fixture generator CLI.
//   node src/cli.ts                 write golden/fixtures/** and manifest.json
//   node src/cli.ts --check         fail if the committed fixtures differ from the generator
//   node src/cli.ts --scale <dir>   write the F9 scale sets (not committed) to <dir>
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { allFixtures, scaleFixtures } from "./index.ts";
import type { Fixture } from "./types.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../../golden/fixtures");

const sha256 = (b: Uint8Array): string => createHash("sha256").update(b).digest("hex");

function manifest(fixtures: readonly Fixture[], scale: readonly Fixture[]): string {
  const entry = (f: Fixture): Record<string, unknown> => ({
    id: f.id,
    brand: f.brand,
    set: f.set,
    path: f.path,
    kind: f.kind,
    format: f.format,
    description: f.description,
    variants: f.variants,
    components: f.components,
    compare: f.compare,
    committed: f.committed !== false,
    bytes: f.bytes.length,
    sha256: sha256(f.bytes),
  });
  return JSON.stringify({
    note: "Every fixture is fictional and generated by tools/fixture-gen (seeded, deterministic). No real trades, accounts, people or paths.",
    generator: "tools/fixture-gen",
    fixtures: [...fixtures, ...scale].map(entry),
  }, null, 2) + "\n";
}

function main(argv: readonly string[]): number {
  const fixtures = allFixtures();
  const ids = new Set<string>();
  for (const f of fixtures) {
    if (ids.has(f.id)) throw new Error(`duplicate fixture id ${f.id}`);
    ids.add(f.id);
  }
  const scaleIdx = argv.indexOf("--scale");
  if (scaleIdx >= 0) {
    const out = resolve(argv[scaleIdx + 1] ?? "f9");
    for (const f of scaleFixtures()) {
      const p = join(out, f.path);
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, f.bytes);
      console.log(`${f.path}  ${f.bytes.length} bytes`);
    }
    return 0;
  }
  const scale = scaleFixtures();
  const text = manifest(fixtures, scale);

  if (argv.includes("--check")) {
    let bad = 0;
    for (const f of fixtures) {
      const p = join(root, f.path);
      if (!existsSync(p) || sha256(readFileSync(p)) !== sha256(f.bytes)) {
        console.error(`differs: ${f.path}`);
        bad++;
      }
    }
    const mp = join(root, "manifest.json");
    if (!existsSync(mp) || readFileSync(mp, "utf8") !== text) {
      console.error("differs: manifest.json");
      bad++;
    }
    console.log(bad ? `${bad} file(s) differ from the generator` : `${fixtures.length} fixtures match the generator`);
    return bad ? 1 : 0;
  }

  for (const brand of ["dojix", "greenwick"]) rmSync(join(root, brand), { recursive: true, force: true });
  for (const f of fixtures) {
    const p = join(root, f.path);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, f.bytes);
  }
  writeFileSync(join(root, "manifest.json"), text);
  console.log(`wrote ${fixtures.length} fixtures (+${scale.length} scale sets in the manifest only) to ${root}`);
  return 0;
}

process.exitCode = main(process.argv.slice(2));
