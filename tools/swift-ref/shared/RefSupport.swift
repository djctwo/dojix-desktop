// Shared support for the Swift reference harness (tools/swift-ref). Copied next to the app
// sources of each brand by prepare.mjs; compiled into the same module as the app code.
//
// Turns any Swift value into JSON through reflection, so the harness never has to know a
// component's result types. Rules (mirrored by tools/parity-check):
//   Double  → JSON number using Swift's shortest round-trip text; ±∞/NaN → "Infinity"/"-Infinity"/"NaN"
//   Int     → number; |n| > 2^53 → decimal string
//   Decimal → string (Swift `description`, e.g. "1.2345")
//   Date    → "yyyy-MM-ddTHH:mm:ss.SSSZ" (UTC)
//   Trade   → "#<ticket>" inside analytics outputs (the full trade is in the import section)
//   enum    → raw value when it has one, else the case name; payload cases → {"$case", "values"}
//   struct  → object of stored properties (+ computed ones exposed via RefDumpable)
//   Calendar → {identifier, firstWeekday, minimumDaysInFirstWeek, timeZone, locale} (its public
//              settings, not Foundation's reflected internals); TimeZone / Locale → identifier
//   UUID, closures and UI values (colours, fonts, images) are omitted.
import Foundation

indirect enum RefJSON {
    case null
    case bool(Bool)
    case int(Int64)
    case double(Double)
    case string(String)
    case array([RefJSON])
    case object([(String, RefJSON)])
    case omit
}

/// Computed properties of a result type, generated by prepare.mjs.
protocol RefDumpable {
    var refExtras: [(String, Any)] { get }
}

/// One named value read lazily from a component.
struct RefOutput {
    let key: String
    let get: @MainActor () -> Any
    init(_ key: String, _ get: @escaping @MainActor () -> Any) {
        self.key = key
        self.get = get
    }
}

struct RefContext {
    let trades: [Trade]
