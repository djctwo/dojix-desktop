    let lastClose: Date
}

@MainActor
enum RefFormat {
    static let iso: ISO8601DateFormatter = {
        let f = ISO8601DateFormatter()
        f.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        f.timeZone = TimeZone(identifier: "UTC")
        return f
    }()
    static let isoPlain: ISO8601DateFormatter = {
        let f = ISO8601DateFormatter()
        f.formatOptions = [.withInternetDateTime]
        return f
    }()

    static func date(_ s: String) -> Date? { iso.date(from: s) ?? isoPlain.date(from: s) }
}

/// SwiftUI/AppKit value types that carry no numbers (compared by base name, generics stripped).
private let uiTypeNames: Set<String> = ["Color", "Font", "Image", "AnyView", "Gradient", "LinearGradient", "RadialGradient",
                                        "AngularGradient", "AnyShapeStyle", "NSColor", "NSImage", "Text", "Binding",
                                        "ModifiedContent", "LocalizedStringKey", "AttributedString"]

/// A Calendar by the settings a component can observe (the reflected storage holds ICU internals).
func refCalendar(_ c: Calendar) -> RefJSON {
    .object([
        ("firstWeekday", .int(Int64(c.firstWeekday))),
        ("identifier", .string(String(describing: c.identifier))),
        ("locale", c.locale.map { RefJSON.string($0.identifier) } ?? RefJSON.null),
        ("minimumDaysInFirstWeek", .int(Int64(c.minimumDaysInFirstWeek))),
        ("timeZone", .string(c.timeZone.identifier)),
    ])
}

@MainActor
func refEncode(_ value: Any, depth: Int = 0) -> RefJSON {
    if depth > 16 { return .string("$max-depth") }
    switch value {
    case let v as RefJSON: return v
    case let v as Bool: return .bool(v)
    case let v as Int: return refInt(Int64(v))
    case let v as Int64: return refInt(v)
    case let v as Int32: return .int(Int64(v))
    case let v as UInt64: return v > 9_007_199_254_740_992 ? .string(String(v)) : .int(Int64(v))
    case let v as UInt: return v > 9_007_199_254_740_992 ? .string(String(v)) : .int(Int64(v))
    case let v as Double: return refDouble(v)
    case let v as Float: return refDouble(Double(v))
    case let v as CGFloat: return refDouble(Double(v))
    case let v as Decimal: return .string(v.description)
    case let v as String: return .string(v)
    case let v as Substring: return .string(String(v))
    case let v as Character: return .string(String(v))
    case let v as Date: return .string(RefFormat.iso.string(from: v))
    case is UUID: return .omit
    case let v as URL: return .string(v.lastPathComponent)
    case let v as Trade: return .string("#\(v.ticket)")
    case let v as Calendar: return refCalendar(v)
    case let v as TimeZone: return .string(v.identifier)
    case let v as Locale: return .string(v.identifier)
    default: break
    }
    let typeName = String(describing: type(of: value))
    let baseName = String(typeName.split(separator: "<").first ?? "")
    if typeName.contains("->") || uiTypeNames.contains(baseName) { return .omit }
    let mirror = Mirror(reflecting: value)
    switch mirror.displayStyle {
    case .optional:
        guard let child = mirror.children.first else { return .null }
        return refEncode(child.value, depth: depth + 1)
    case .collection:
        let items = mirror.children.map { refEncode($0.value, depth: depth + 1) }.filter { !$0.isOmit }
        return .array(items)
    case .set:
        let items = mirror.children.map { refEncode($0.value, depth: depth + 1) }.filter { !$0.isOmit }
        return .array(items.sorted { refSerialize($0) < refSerialize($1) })
    case .dictionary:
        var pairs: [(String, RefJSON)] = []
        for child in mirror.children {
            let kv = Array(Mirror(reflecting: child.value).children)
            guard kv.count == 2 else { continue }
            let key = refKeyString(kv[0].value)
            let v = refEncode(kv[1].value, depth: depth + 1)
            if !v.isOmit { pairs.append((key, v)) }
        }
        return .object(pairs.sorted { $0.0 < $1.0 })
    case .enum:
        if mirror.children.isEmpty {
            if let raw = (value as? any RawRepresentable)?.rawValue {
                var obj: [(String, RefJSON)] = []
                let rawJSON = refEncode(raw, depth: depth + 1)
                if let d = value as? RefDumpable {
                    obj = [("$case", .string(String(describing: value))), ("$raw", rawJSON)]
                    obj += refExtras(d, depth: depth)
                    return .object(obj)
                }
                return rawJSON
            }
            if let d = value as? RefDumpable {
                return .object([("$case", .string(String(describing: value)))] + refExtras(d, depth: depth))
            }
            return .string(String(describing: value))
        }
        guard let child = mirror.children.first else { return .string(String(describing: value)) }
        return .object([("$case", .string(child.label ?? "?")), ("values", refEncode(child.value, depth: depth + 1))])
    case .tuple:
        let labelled = mirror.children.contains { !($0.label ?? ".").hasPrefix(".") }
        if labelled {
            return .object(mirror.children.compactMap { c in
                let v = refEncode(c.value, depth: depth + 1)
                return v.isOmit ? nil : (c.label ?? "?", v)
            }.sorted { $0.0 < $1.0 })
        }
        return .array(mirror.children.map { refEncode($0.value, depth: depth + 1) })
    case .struct, .class:
        var obj: [(String, RefJSON)] = []
        for c in mirror.children {
            guard let label = c.label else { continue }
            let v = refEncode(c.value, depth: depth + 1)
            if !v.isOmit { obj.append((label, v)) }
        }
        if let d = value as? RefDumpable {
            let names = Set(obj.map(\.0))
            obj += refExtras(d, depth: depth).filter { !names.contains($0.0) }
        }
        return .object(obj.sorted { $0.0 < $1.0 })
    default:
        return .string(String(describing: value))
    }
}

@MainActor
private func refExtras(_ d: RefDumpable, depth: Int) -> [(String, RefJSON)] {
    d.refExtras.compactMap { name, v in
        let j = refEncode(v, depth: depth + 1)
        return j.isOmit ? nil : (name, j)
    }
}

private func refInt(_ v: Int64) -> RefJSON {
    abs(Double(v)) > 9_007_199_254_740_992 ? .string(String(v)) : .int(v)
}

func refDouble(_ v: Double) -> RefJSON {
    if v.isNaN { return .string("NaN") }
    if v.isInfinite { return .string(v > 0 ? "Infinity" : "-Infinity") }
    return .double(v)
}

@MainActor
private func refKeyString(_ key: Any) -> String {
    switch refEncode(key) {
    case .string(let s): return s
    case .int(let i): return String(i)
    case .double(let d): return "\(d)"
    case .bool(let b): return b ? "true" : "false"
    case let other: return refSerialize(other)
    }
}

extension RefJSON {
    var isOmit: Bool {
        if case .omit = self { return true }
        return false
    }
}

/// Compact, deterministic JSON text.
func refSerialize(_ j: RefJSON, indent: Int? = nil, level: Int = 0) -> String {
    let nl = indent == nil ? "" : "\n"
    let pad = { (n: Int) in indent.map { String(repeating: " ", count: $0 * n) } ?? "" }
    let sep = indent == nil ? ":" : ": "
    switch j {
    case .null, .omit: return "null"
    case .bool(let b): return b ? "true" : "false"
    case .int(let i): return String(i)
    case .double(let d): return "\(d)"
    case .string(let s): return refQuote(s)
    case .array(let a):
        if a.isEmpty { return "[]" }
        let inner = a.map { pad(level + 1) + refSerialize($0, indent: indent, level: level + 1) }
        return "[" + nl + inner.joined(separator: "," + nl) + nl + pad(level) + "]"
    case .object(let o):
        let kept = o.filter { !$0.1.isOmit }
        if kept.isEmpty { return "{}" }
        let inner = kept.map { pad(level + 1) + refQuote($0.0) + sep + refSerialize($0.1, indent: indent, level: level + 1) }
        return "{" + nl + inner.joined(separator: "," + nl) + nl + pad(level) + "}"
    }
}

func refQuote(_ s: String) -> String {
    var out = "\""
    for scalar in s.unicodeScalars {
        switch scalar {
        case "\"": out += "\\\""
        case "\\": out += "\\\\"
        case "\n": out += "\\n"
        case "\r": out += "\\r"
        case "\t": out += "\\t"
        default:
            if scalar.value < 0x20 || scalar.value == 0x7F || (0x80...0x9F).contains(scalar.value)
                || scalar.value == 0x2028 || scalar.value == 0x2029 {
                out += String(format: "\\u%04x", scalar.value)
            } else {
                out.unicodeScalars.append(scalar)
            }
        }
    }
    return out + "\""
}

// MARK: - Process plumbing

/// Progress marker on stderr: the driver reads the last one after a crash and skips that key.
func refMark(_ key: String) {
    FileHandle.standardError.write(Data("@@ \(key)\n".utf8))
}

func refLog(_ message: String) {
    FileHandle.standardError.write(Data("swift-ref: \(message)\n".utf8))
}

struct RefArgs {
    var values: [String: String] = [:]
    init(_ argv: [String]) {
        var i = 1
        while i < argv.count {
            let a = argv[i]
            if a.hasPrefix("--"), i + 1 < argv.count {
                values[String(a.dropFirst(2))] = argv[i + 1]
                i += 2
            } else {
                i += 1 // -AppleLocale xx and other defaults arguments are read by Foundation
            }
        }
    }
    subscript(_ key: String) -> String? { values[key] }
}

/// Runs each output, skipping keys that crashed or hung in an earlier attempt.
@MainActor
func refEvaluate(_ outputs: [RefOutput], skip: [String: String]) -> [(String, RefJSON)] {
    var result: [(String, RefJSON)] = []
    var seen: [String: Int] = [:]
    for o in outputs {
        var key = o.key
        if let n = seen[key] { key += "#\(n + 1)" }
        seen[o.key, default: 0] += 1
        if let reason = skip[key] {
            result.append((key, .object([("$skipped", .string(reason))])))
            continue
        }
        refMark(key)
        result.append((key, refEncode(o.get())))
    }
    return result
}

/// Doubles from a JSON fixture value: a number, or a string such as "NaN" / "Infinity".
func refDoubleValue(_ v: Any?) -> Double {
    if let n = v as? NSNumber { return n.doubleValue }
    if let s = v as? String { return Double(s) ?? 0 }
    return 0
}

func refIntValue(_ v: Any?) -> Int {
    if let n = v as? NSNumber { return n.intValue }
    if let s = v as? String { return Int(s) ?? 0 }
    return 0
}

func refInt64Value(_ v: Any?) -> Int64 {
    if let s = v as? String { return Int64(s) ?? 0 }
    if let n = v as? NSNumber { return n.int64Value }
    return 0
}

func refDecimalValue(_ v: Any?) -> Decimal {
    if let s = v as? String { return Decimal(string: s, locale: Locale(identifier: "en_US_POSIX")) ?? 0 }
    if let n = v as? NSNumber { return Decimal(string: n.stringValue, locale: Locale(identifier: "en_US_POSIX")) ?? 0 }
    return 0
}

func refStringValue(_ v: Any?) -> String { (v as? String) ?? "" }
func refBoolValue(_ v: Any?) -> Bool { (v as? Bool) ?? ((v as? NSNumber)?.boolValue ?? false) }
